import { chromium } from "playwright";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const BASE_URL = process.env.BASE_URL || "http://localhost:3000";
const OUT_DIR = path.join(process.cwd(), "public", "pages");
const DATA_FILE = path.join(process.cwd(), "app", "data", "leafthrough-pages.ts");
const LOCALES = ["EN", "ID", "ZH"];
const pad = (n) => String(n).padStart(2, "0");

const browser = await chromium.launch();
const context = await browser.newContext({
  viewport: { width: 1200, height: 1560 },
  deviceScaleFactor: 1,
});
const page = await context.newPage();
const result = {};

try {
  for (const locale of LOCALES) {
    await mkdir(path.join(OUT_DIR, locale), { recursive: true });
    result[locale] = [];

    for (let pageNumber = 1; pageNumber <= 12; pageNumber++) {
      await page.goto(`${BASE_URL}/render?locale=${locale}&page=${pageNumber}`, {
        waitUntil: "networkidle",
      });
      await page.addStyleTag({
        content: "nextjs-portal { display: none !important; }",
      });
      await page.evaluate(() => document.fonts.ready);

      const root = page.locator("[data-page-root]");
      await root.waitFor();
      const text = (await root.innerText()).trim();
      const src = `/pages/${locale}/${pad(pageNumber)}.webp`;

      await root.screenshot({
        path: path.join(OUT_DIR, locale, `${pad(pageNumber)}.webp`),
        type: "webp",
        quality: 92,
      });

      result[locale].push({
        src,
        alt: `AGRI Issue 01, ${locale} page ${pageNumber}`,
        text,
      });
      console.log(`${locale} ${pad(pageNumber)} -> ${src}`);
    }
  }

  const contents = `import type { Locale } from "./agri-catalog";\n\nexport interface LeafThroughPage {\n  src: string;\n  alt: string;\n  text: string;\n}\n\n// Generated by scripts/capture-pages.mjs. Do not edit by hand.\nexport const LEAFTHROUGH_PAGES: Record<Locale, LeafThroughPage[]> = ${JSON.stringify(result, null, 2)};\n`;
  await writeFile(DATA_FILE, contents, "utf8");
  console.log(`Wrote ${DATA_FILE}`);
} finally {
  await browser.close();
}
